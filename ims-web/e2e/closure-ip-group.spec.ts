import { test, expect } from '@playwright/test'
import { attachClosurePageHooks, loginAdmin } from './closure-helpers'

test.describe('IP 组 BUG-014～021 / BUG-024', () => {
  test.skip(!!process.env.SKIP_E2E, 'SKIP_E2E set — 跳过 Playwright')

  test('新建、编辑、成员、停用，且页头没有导出', async ({ page }) => {
    test.setTimeout(120_000)
    const pageErrors = attachClosurePageHooks(page)
    await loginAdmin(page)
    const stamp = String(Date.now()).slice(-6)
    const bigName = `E2E大组${stamp}`
    const smallName = `E2E小组${stamp}`

    await page.goto('/ims/ip-group')
    await expect(page.locator('h1')).toHaveText('IP 组运营')
    await expect(page.getByRole('button', { name: '导出' })).toHaveCount(0)

    await page.getByRole('button', { name: '+ 新建大组' }).click()
    const drawer = page.getByTestId('ipg-group-drawer')
    await expect(drawer).toBeVisible()
    await expect(drawer.locator('input[value="SMALL"]')).toBeDisabled()
    await expect(drawer.getByTestId('ipg-parent')).toBeDisabled()
    await drawer.getByTestId('ipg-group-submit').click()
    await expect(drawer.getByTestId('ipg-name-err')).toHaveText('必填项，请填写')
    await drawer.getByTestId('ipg-name').fill('组'.repeat(51))
    await drawer.getByTestId('ipg-group-submit').click()
    await expect(drawer.getByTestId('ipg-name-err')).toHaveText('名称长度 1-50 字符')

    await drawer.getByTestId('ipg-name').fill(bigName)
    await drawer.getByTestId('ipg-leader').selectOption({ label: '管理员' })
    await drawer.getByTestId('ipg-level').selectOption({ label: 'A级' })
    await drawer.getByTestId('ipg-desc').fill('大组说明')
    await drawer.getByTestId('ipg-group-submit').click()
    await expect(page.getByTestId('ipg-toast')).toContainText('已创建 IP 组')
    const bigNode = page.locator('.ipg-node', { hasText: bigName })
    await expect(bigNode).toBeVisible()
    await expect(page.getByTestId('ipg-meta')).toContainText('组长：管理员')
    await expect(page.getByTestId('ipg-basic')).toContainText('管理员')
    await expect(page.getByTestId('ipg-basic')).toContainText('A级')

    await page.getByRole('button', { name: '+ 新建小组' }).click()
    const smallDrawer = page.getByTestId('ipg-group-drawer')
    await expect(smallDrawer.locator('input[value="BIG"]')).toBeDisabled()
    await expect(smallDrawer.getByTestId('ipg-parent').locator('option:checked')).toHaveText(bigName)
    await smallDrawer.getByTestId('ipg-name').fill(smallName)
    await smallDrawer.getByTestId('ipg-group-submit').click()
    await expect(page.getByTestId('ipg-toast')).toContainText('已创建 IP 组')
    await page.locator('.ipg-node', { hasText: smallName }).click()
    await expect(page.getByRole('button', { name: '+ 新建小组' })).toHaveCount(0)
    await expect(page.getByTestId('ipg-basic')).toContainText(bigName)
    await expect(page.getByTestId('ipg-meta')).toContainText('创建于')

    const beforeUpdated = await page.getByTestId('ipg-updated').innerText()
    await page.waitForTimeout(1100)
    await page.getByTestId('ipg-edit').click()
    const editDrawer = page.getByTestId('ipg-group-drawer')
    await expect(editDrawer).toContainText('编辑 IP 组')
    await expect(editDrawer.locator('input[value="BIG"]')).toBeDisabled()
    await expect(editDrawer.locator('input[value="SMALL"]')).toBeDisabled()
    await editDrawer.getByTestId('ipg-desc').fill('小组备注')
    await editDrawer.getByTestId('ipg-sort-input').fill('6')
    await editDrawer.getByTestId('ipg-group-submit').click()
    await expect(page.getByTestId('ipg-toast')).toContainText('已保存')
    await expect(page.getByTestId('ipg-remark')).toHaveText('小组备注')
    await expect(page.getByTestId('ipg-sort')).toHaveText('6')
    await expect(page.getByTestId('ipg-updated')).not.toHaveText(beforeUpdated)

    await page.locator('.tab', { hasText: '成员管理' }).click()
    await page.getByTestId('ipg-add-member').click()
    const memberDrawer = page.getByTestId('ipg-member-drawer')
    await memberDrawer.getByTestId('ipg-member-submit').click()
    await expect(memberDrawer.getByTestId('ipg-member-user-err')).toHaveText('必填项，请填写')
    await expect(memberDrawer.getByTestId('ipg-member-position-err')).toHaveText('必填项，请填写')
    await expect(memberDrawer.getByTestId('ipg-member-relation')).toHaveValue('PRIMARY')
    await expect(memberDrawer.getByTestId('ipg-member-position')).toHaveJSProperty('tagName', 'SELECT')
    await memberDrawer.getByTestId('ipg-member-user').selectOption({ label: '管理员' })
    await memberDrawer.getByTestId('ipg-member-position').selectOption({ label: '编辑' })
    await memberDrawer.getByTestId('ipg-member-submit').click()
    await expect(page.getByTestId('ipg-toast')).toContainText('已添加成员')
    const row = page.getByTestId('ipg-member-row')
    await expect(row).toContainText('管理员')
    await expect(row.getByTestId('ipg-member-position-cell')).toHaveText('编辑')
    await expect(row.getByTestId('ipg-member-relation-cell')).toHaveText('主职')
    await expect(page.locator('.ipg-node.on .cnt')).toContainText('(1/')

    await row.getByTestId('ipg-member-edit').click()
    await expect(page.getByTestId('ipg-member-drawer')).toContainText('编辑成员')
    await page.getByTestId('ipg-member-relation').selectOption({ label: '兼职' })
    await page.getByTestId('ipg-member-position').selectOption({ label: '直播运营' })
    await page.getByTestId('ipg-member-submit').click()
    await expect(page.getByTestId('ipg-toast')).toContainText('成员已保存')
    await expect(row.getByTestId('ipg-member-position-cell')).toHaveText('直播运营')
    await expect(row.getByTestId('ipg-member-relation-cell')).toHaveText('兼职')

    await row.getByTestId('ipg-member-remove').click()
    await expect(page.getByTestId('ipg-confirm-text')).toContainText('管理员')
    await page.getByTestId('ipg-confirm-cancel').click()
    await expect(row).toBeVisible()
    await row.getByTestId('ipg-member-remove').click()
    await page.getByTestId('ipg-confirm-ok').click()
    await expect(page.getByTestId('ipg-toast')).toContainText('成员已移除')
    await expect(page.locator('.ipg-node.on .cnt')).toContainText('(0/')

    await page.getByTestId('ipg-toggle').click()
    await expect(page.getByTestId('ipg-toast')).toContainText('状态已更新为「停用」')
    await expect(page.getByTestId('ipg-toggle')).toHaveText('启用')
    await expect(page.getByTestId('ipg-status')).toHaveText('停用')
    await page.getByTestId('ipg-toggle').click()
    await expect(page.getByTestId('ipg-toast')).toContainText('状态已更新为「启用」')
    await expect(page.getByTestId('ipg-status')).toHaveText('启用')

    await page.getByTestId('ipg-delete').click()
    await expect(page.getByTestId('ipg-confirm-text')).toContainText(smallName)
    await page.getByTestId('ipg-confirm-cancel').click()
    await expect(page.locator('.ipg-node', { hasText: smallName })).toBeVisible()

    expect(pageErrors).toEqual([])
  })

  test('BUG-025 搜索小组带出上级，搜索大组不展开', async ({ page }) => {
    test.setTimeout(90_000)
    const pageErrors = attachClosurePageHooks(page)
    await loginAdmin(page)
    const stamp = String(Date.now()).slice(-6)
    const bigName = `搜大组${stamp}`
    const smallName = `搜小组${stamp}`
    const otherSmall = `搜其他${stamp}`

    await page.goto('/ims/ip-group')
    await expect(page.locator('h1')).toHaveText('IP 组运营')
    await page.getByRole('button', { name: '+ 新建大组' }).click()
    const drawer = page.getByTestId('ipg-group-drawer')
    await drawer.getByTestId('ipg-name').fill(bigName)
    await drawer.getByTestId('ipg-group-submit').click()
    await expect(page.locator('.ipg-node', { hasText: bigName })).toBeVisible()

    await page.getByRole('button', { name: '+ 新建小组' }).click()
    await page.getByTestId('ipg-name').fill(smallName)
    await page.getByTestId('ipg-group-submit').click()
    await page.locator('.ipg-node', { hasText: bigName }).click()
    await page.getByRole('button', { name: '+ 新建小组' }).click()
    await page.getByTestId('ipg-name').fill(otherSmall)
    await page.getByTestId('ipg-group-submit').click()

    await page.getByTestId('ipg-search').fill(smallName)
    await expect(page.locator('.ipg-node', { hasText: bigName })).toBeVisible()
    await expect(page.locator('.ipg-node', { hasText: smallName })).toBeVisible()
    await expect(page.locator('.ipg-node', { hasText: otherSmall })).toHaveCount(0)

    await page.getByTestId('ipg-search').fill(bigName)
    await expect(page.locator('.ipg-node', { hasText: bigName })).toBeVisible()
    await expect(page.locator('.ipg-node', { hasText: smallName })).toHaveCount(0)
    await expect(page.locator('.ipg-node', { hasText: otherSmall })).toHaveCount(0)
    expect(pageErrors).toEqual([])
  })
})
